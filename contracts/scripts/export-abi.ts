// Writes the ABIs that lib/ needs to lib/wave-abi.ts. Run it after a compile.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const names = ['WaveAccount', 'WaveAccountFactory', 'WaveGasStation', 'AgentKeyFrameValidator', 'TestUSDC']
const body = names
  .map((n) => {
    const { abi } = JSON.parse(readFileSync(path.join(ROOT, 'artifacts/src', `${n}.sol`, `${n}.json`), 'utf8'))
    return `export const ${n}Abi = ${JSON.stringify(abi)} as const\n`
  })
  .join('\n')
const file = path.resolve(ROOT, '../lib/wave-abi.ts')
writeFileSync(file, `// Generated by contracts/scripts/export-abi.ts. Do not edit.\n\n${body}`)
console.log('wrote', file)
